// Generates src/tdb-series.ts from ERFA's dtdb.c, the full Fairhead &
// Bretagnon (1990) TDB−TT series. The coefficient literals are copied
// verbatim, so every double in the generated table is the one ERFA compiles.
//
//   curl -sSfLO https://raw.githubusercontent.com/liberfa/erfa/v2.0.1/src/dtdb.c
//   node scripts/generate-tdb-series.mjs dtdb.c > src/tdb-series.ts
//
// The input is checked against the SHA-256 of the pinned ERFA release so a
// different or modified source cannot silently change the physical model.
import { createHash } from 'node:crypto'
import { readFileSync } from 'node:fs'

const ERFA_TAG = 'v2.0.1'
const DTDB_SHA256 = '228bd7c7c1c88dda44c29a076f289c968f64d77a2dc389138b03ab5d1d442105'
const TERMS = 787
/** First index of each T^n block in ERFA's table, plus the end. */
const BLOCK_STARTS = [0, 474, 679, 764, 784, 787]

const [input] = process.argv.slice(2)
if (input === undefined) throw new Error('usage: generate-tdb-series.mjs <dtdb.c>')
const source = readFileSync(input)
const digest = createHash('sha256').update(source).digest('hex')
if (digest !== DTDB_SHA256) {
  throw new Error(`dtdb.c SHA-256 ${digest} does not match ERFA ${ERFA_TAG} (${DTDB_SHA256})`)
}

const text = source.toString('utf8')
const table = /fairhd\[787\]\[3\] = \{([\s\S]*?)\n {3}\};/.exec(text)?.[1]
if (table === undefined) throw new Error('fairhd table not found')
const NUMBER = String.raw`([+-]?\d+(?:\.\d+)?(?:e[+-]?\d+)?)`
const row = new RegExp(String.raw`\{\s*${NUMBER},\s*${NUMBER},\s*${NUMBER}\s*\}`, 'g')
const rows = [...table.matchAll(row)].map((match) => match.slice(1, 4))
if (rows.length !== TERMS) throw new Error(`expected ${TERMS} terms, found ${rows.length}`)
for (const values of rows) {
  for (const value of values) {
    if (!Number.isFinite(Number(value))) throw new Error(`non-finite coefficient ${value}`)
  }
}

const lines = rows.map(([amplitude, frequency, phase]) => `  ${amplitude}, ${frequency}, ${phase},`)
process.stdout
  .write(`// Generated by scripts/generate-tdb-series.mjs from ERFA ${ERFA_TAG} src/dtdb.c
// (SHA-256 ${DTDB_SHA256}). Do not edit by hand.
//
// Fairhead, L. & Bretagnon, P. (1990), A&A 229, 240, as adapted in ERFA:
// Copyright (C) 2013-2021, NumFOCUS Foundation. Derived, with permission, from
// the IAU SOFA library. Used under the ERFA BSD 3-clause licence reproduced in
// THIRD-PARTY-NOTICES.md.

/**
 * The ${TERMS}-term Fairhead & Bretagnon TDB−TT series as flat
 * \`[amplitude (s), frequency (rad / Julian millennium), phase (rad)]\` triples,
 * in ERFA order. A typed array: summing the series reads it 2 361 times per
 * evaluation, and packed doubles are several times faster than a frozen array.
 * Internal; never exposed, so its mutability is not a public contract.
 */
export const FAIRHEAD_BRETAGNON_TERMS: Float64Array = new Float64Array([
${lines.join('\n')}
])

/** Term index where each power-of-T block starts (T^0 … T^4), plus the end. */
export const FAIRHEAD_BRETAGNON_BLOCKS = Object.freeze([${BLOCK_STARTS.join(', ')}] as const)
`)
