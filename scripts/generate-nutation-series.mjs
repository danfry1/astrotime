// Generates src/nutation-series.ts from ERFA's nut00a.c (the IAU 2000A
// nutation series) and eect00.c (the complementary terms of the equation of
// the equinoxes). Coefficient literals are copied verbatim, so every value in
// the generated tables is the one ERFA compiles.
//
//   for f in nut00a eect00; do
//     curl -sSfLO https://raw.githubusercontent.com/liberfa/erfa/v2.0.1/src/$f.c
//   done
//   node scripts/generate-nutation-series.mjs nut00a.c eect00.c > src/nutation-series.ts
//
// Each input is checked against the SHA-256 of the pinned ERFA release.
import { createHash } from 'node:crypto'
import { readFileSync } from 'node:fs'

const ERFA_TAG = 'v2.0.1'
const SOURCES = {
  'nut00a.c': 'a1538ec0277745db974ab76ca4b678a7602249bccecf9474e2b0268f9c2032ef',
  'eect00.c': '771d6e118a12b8fdc80894ea0a6c55f63ce2c9a407c75fd176aafb80b43ed4a2',
}
const NUMBER = /^[+-]?\d+(?:\.\d+)?(?:e[+-]?\d+)?$/

/** @param {string} path @param {'nut00a.c' | 'eect00.c'} name */
function read(path, name) {
  const source = readFileSync(path)
  const digest = createHash('sha256').update(source).digest('hex')
  const expected = SOURCES[name]
  if (digest !== expected) {
    throw new Error(`${name} SHA-256 ${digest} does not match ERFA ${ERFA_TAG} (${expected})`)
  }
  return source.toString('utf8')
}

function block(text, opening) {
  const start = text.indexOf(opening)
  if (start === -1) throw new Error(`${opening} not found`)
  return text.slice(start + opening.length, text.indexOf('\n   };', start))
}

/**
 * @param {string} body
 * @param {number} columns
 * @param {RegExp} pattern
 * @returns {string[][]}
 */
function rows(body, columns, pattern) {
  const found = [...body.matchAll(pattern)].map((match) =>
    match
      .slice(1)
      .join(',')
      .split(',')
      .map((value) => value.trim()),
  )
  for (const values of found) {
    if (values.length !== columns || !values.every((value) => NUMBER.test(value))) {
      throw new Error(`malformed row: ${values.join(', ')}`)
    }
  }
  return found
}

const [nut00aPath, eect00Path] = process.argv.slice(2)
if (nut00aPath === undefined || eect00Path === undefined) {
  throw new Error('usage: generate-nutation-series.mjs <nut00a.c> <eect00.c>')
}
const nut00a = read(nut00aPath, 'nut00a.c')
const eect00 = read(eect00Path, 'eect00.c')

const FLAT = /\{([^{}]*)\}/g
const luniSolar = rows(block(nut00a, '} xls[] = {'), 11, FLAT)
const planetary = rows(block(nut00a, '} xpl[] = {'), 17, FLAT)
const NESTED = /\{\{([^{}]*)\},([^{}]*)\}/g
const complementary0 = rows(block(eect00, 'static const TERM e0[] = {'), 10, NESTED)
const complementary1 = rows(block(eect00, 'static const TERM e1[] = {'), 10, NESTED)
for (const { name, table, expected } of [
  { name: 'luni-solar', table: luniSolar, expected: 678 },
  { name: 'planetary', table: planetary, expected: 687 },
  { name: 'complementary t^0', table: complementary0, expected: 33 },
  { name: 'complementary t^1', table: complementary1, expected: 1 },
]) {
  if (table.length !== expected) {
    throw new Error(`${name}: ${String(table.length)} rows, expected ${String(expected)}`)
  }
}

const emit = (table) => table.map((values) => `  ${values.join(', ')},`).join('\n')
process.stdout.write(`// Generated by scripts/generate-nutation-series.mjs from ERFA ${ERFA_TAG}
// src/nut00a.c (SHA-256 ${SOURCES['nut00a.c']}) and
// src/eect00.c (SHA-256 ${SOURCES['eect00.c']}). Do not edit by hand.
//
// IAU 2000A nutation (Mathews, Herring & Buffett 2002) and the IERS 2003
// complementary terms of the equation of the equinoxes, as adapted in ERFA:
// Copyright (C) 2013-2023, NumFOCUS Foundation. Derived, with permission, from
// the IAU SOFA library. Used under the ERFA BSD 3-clause licence reproduced in
// THIRD-PARTY-NOTICES.md. Typed arrays, internal and never exposed.

/**
 * Luni-solar terms, 11 per row: multipliers of l, l′, F, D, Ω, then longitude
 * sin, t·sin and cos and obliquity cos, t·cos and sin coefficients, in units
 * of 0.1 µas (per Julian century for the t terms).
 */
export const NUTATION_LUNI_SOLAR: Float64Array = /* @__PURE__ */ new Float64Array([
${emit(luniSolar)}
])

/**
 * Planetary terms, 17 per row: multipliers of l, F, D, Ω, the longitudes of
 * Mercury to Neptune and the general precession, then longitude sin and cos
 * and obliquity sin and cos coefficients, in units of 0.1 µas.
 */
export const NUTATION_PLANETARY: Float64Array = /* @__PURE__ */ new Float64Array([
${emit(planetary)}
])

/**
 * Equation-of-the-equinoxes complementary terms, 10 per row: multipliers of
 * l, l′, F, D, Ω, L_Ve, L_E, p_A, then sin and cos coefficients in
 * arcseconds. The first 33 rows are of order t^0, the last of order t^1.
 */
export const EQUINOX_COMPLEMENTARY: Float64Array = /* @__PURE__ */ new Float64Array([
${emit([...complementary0, ...complementary1])}
])
`)
